import { join } from "node:path";
import { ConfigError, type McpServerConfig, type MergedConfig, type Skill } from "@harnessd/shared";
import { jsonFile, tomlKey, tomlString, tomlStringArray, yamlString } from "./format.ts";

/**
 * One file `harnessd sync` owns, relative to the repo root with `/` separators.
 * `copyFrom` is an absolute source path, copied byte for byte with its executable bit.
 */
export type SyncFile =
  | { path: string; content: string }
  | { path: string; symlinkTarget: string }
  | { path: string; copyFrom: string };

/** Where each harness reads repo skills: Claude Code, then Codex. */
export const SKILL_ROOTS = [".claude/skills", ".agents/skills"] as const;

export const GENERATED_NOTE =
  "Generated by `harnessd sync`. Do not edit: change .harnessd/ and run `harnessd sync`.";

const SKILL_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

/** The built-in memory server (D-005). An `[mcp.harnessd-memory]` table replaces it. */
export const MEMORY_SERVER: { name: string; server: McpServerConfig } = {
  name: "harnessd-memory",
  server: { command: "harnessd", args: ["mcp", "memory"] },
};

/** Configured MCP servers plus the built-in memory server, sorted by name. */
export function syncedMcpServers(config: MergedConfig): Record<string, McpServerConfig> {
  const all = { [MEMORY_SERVER.name]: MEMORY_SERVER.server, ...config.mcp };
  return Object.fromEntries(Object.entries(all).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/**
 * AGENTS.md: global AGENTS.md, workspace AGENTS.md, then the merged rules.
 * Agent-specific instructions are not here; adapters add them per run.
 */
export function agentsMd(config: MergedConfig): string {
  const parts = [`<!-- ${GENERATED_NOTE} -->`];
  for (const block of config.instructions) {
    const text = block.text.trim();
    if (text !== "") parts.push(text);
  }
  const rules = config.rules.filter((r) => r.text.trim() !== "");
  if (rules.length > 0) {
    parts.push("## Rules");
    for (const rule of rules) parts.push(`### ${rule.name}\n\n${rule.text.trim()}`);
  }
  return `${parts.join("\n\n")}\n`;
}

/** `<skill root>/<name>/SKILL.md`. Frontmatter keys other than name and description stay verbatim. */
export function skillMd(skill: Skill): string {
  const front = [`name: ${yamlString(skill.name)}`];
  if (skill.description !== undefined) front.push(`description: ${yamlString(skill.description)}`);
  front.push(...(skill.frontmatter ?? []));
  const body = skill.body.trim();
  return `---\n${front.join("\n")}\n---\n<!-- ${GENERATED_NOTE} -->\n${body === "" ? "" : `\n${body}\n`}`;
}

function mcpServers(config: MergedConfig): Record<string, Record<string, unknown>> {
  const out: Record<string, Record<string, unknown>> = {};
  for (const [name, server] of Object.entries(syncedMcpServers(config))) {
    const entry: Record<string, unknown> = { command: server.command };
    if (server.args !== undefined) entry.args = server.args;
    if (server.env !== undefined) entry.env = server.env;
    out[name] = entry;
  }
  return out;
}

/** `.claude/settings.json`: pre-approves the project MCP servers from `.mcp.json`. */
export function claudeSettings(config: MergedConfig): string {
  return jsonFile({
    $schema: "https://json.schemastore.org/claude-code-settings.json",
    enabledMcpjsonServers: Object.keys(syncedMcpServers(config)),
  });
}

/** `.mcp.json`, the project MCP file Claude Code reads. */
export function mcpJson(config: MergedConfig): string {
  return jsonFile({ mcpServers: mcpServers(config) });
}

/** `.codex/config.toml` with one `[mcp_servers.<name>]` table per server. */
export function codexConfig(config: MergedConfig): string {
  const lines = [`# ${GENERATED_NOTE}`];
  for (const [name, server] of Object.entries(syncedMcpServers(config))) {
    lines.push("", `[mcp_servers.${tomlKey(name)}]`, `command = ${tomlString(server.command)}`);
    if (server.args !== undefined) lines.push(`args = ${tomlStringArray(server.args)}`);
    if (server.env !== undefined) {
      const pairs = Object.entries(server.env).map(([k, v]) => `${tomlKey(k)} = ${tomlString(v)}`);
      lines.push(`env = ${pairs.length === 0 ? "{}" : `{ ${pairs.join(", ")} }`}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Every native file for a merged config, in a stable order. Pure: no I/O.
 * Codex reads AGENTS.md natively; it gets its config.toml and the skills in `.agents/skills/`.
 */
export function generateSyncFiles(config: MergedConfig): SyncFile[] {
  const files: SyncFile[] = [
    { path: "AGENTS.md", content: agentsMd(config) },
    { path: "CLAUDE.md", symlinkTarget: "AGENTS.md" },
    { path: ".claude/settings.json", content: claudeSettings(config) },
  ];
  for (const skill of config.skills) {
    if (!SKILL_NAME.test(skill.name) || skill.name === "." || skill.name === "..") {
      throw new ConfigError(
        skill.source,
        "name",
        `skill names may only use letters, digits, ".", "_" and "-", got ${JSON.stringify(skill.name)}`,
      );
    }
  }
  for (const root of SKILL_ROOTS) {
    for (const skill of config.skills) {
      files.push({ path: `${root}/${skill.name}/SKILL.md`, content: skillMd(skill) });
      for (const rel of skill.files ?? []) {
        files.push({ path: `${root}/${skill.name}/${rel}`, copyFrom: join(skill.dir, rel) });
      }
    }
  }
  files.push({ path: ".mcp.json", content: mcpJson(config) });
  files.push({ path: ".codex/config.toml", content: codexConfig(config) });
  return files;
}
